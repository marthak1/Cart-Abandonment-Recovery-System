# Makefile

.PHONY: help build up down logs test evidence clean

help:
	@echo "Available commands:"
	@echo "  make build     - Build Docker images"
	@echo "  make up        - Start all services"
	@echo "  make down      - Stop all services"
	@echo "  make logs      - View logs"
	@echo "  make test      - Run tests"
	@echo "  make evidence  - Capture deployment evidence"
	@echo "  make clean     - Clean up containers and volumes"

build:
	docker compose build --no-cache

up:
	docker compose up -d
	@echo "Waiting for services to be healthy..."
	@sleep 30
	@make evidence

down:
	docker compose down

logs:
	docker compose logs -f

test:
	@echo "Running backend tests..."
	cd ecommerce-backend/ecommerce-backend && ./mvnw test
	@echo "Running frontend tests..."
	cd ecommerce-frontend && npm run test:run

evidence:
	@chmod +x scripts/capture-deployment-evidence.sh
	@./scripts/capture-deployment-evidence.sh

clean:
	docker compose down -v
	docker system prune -f